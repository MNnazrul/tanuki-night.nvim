-- Generate terminal themes in extras/ from the palette.
-- Run from repo root:  nvim --headless -u NONE -l scripts/gen_extras.lua
vim.opt.rtp:prepend(vim.fn.getcwd())
local tn = require("tanuki-night")
local c = tn.colors()
local t = tn.terminal_colors(c)
local header = "tanuki-night — GENERATED by scripts/gen_extras.lua"

local function write(path, lines)
  vim.fn.writefile(lines, path)
  print("wrote " .. path)
end

-- kitty
local kitty = {
  "# " .. header,
  "foreground " .. c.fg,
  "background " .. c.bg,
  "selection_foreground none",
  "selection_background " .. c.visual,
  "cursor " .. c.fg,
  "cursor_text_color " .. c.bg,
  "url_color " .. c.blue,
  "active_border_color " .. c.accent,
  "inactive_border_color " .. c.border,
  "active_tab_foreground " .. c.fg,
  "active_tab_background " .. c.bg_hl,
  "inactive_tab_foreground " .. c.comment,
  "inactive_tab_background " .. c.bg_alt2,
  "tab_bar_background " .. c.bg_dark,
}
for i, col in ipairs(t) do
  kitty[#kitty + 1] = ("color%d %s"):format(i - 1, col)
end
write("extras/kitty/tanuki-night.conf", kitty)

-- ghostty
local ghostty = {
  "# " .. header,
  "background = " .. c.bg,
  "foreground = " .. c.fg,
  "cursor-color = " .. c.fg,
  "cursor-text = " .. c.bg,
  "selection-background = " .. c.visual,
  "selection-foreground = " .. c.fg,
}
for i, col in ipairs(t) do
  ghostty[#ghostty + 1] = ("palette = %d=%s"):format(i - 1, col)
end
write("extras/ghostty/tanuki-night", ghostty)

-- alacritty / wezterm (TOML)
local names = { "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white" }
local function q(s)
  return '"' .. s .. '"'
end
local alacritty = {
  "# " .. header,
  "[colors.primary]",
  "background = " .. q(c.bg),
  "foreground = " .. q(c.fg),
  "",
  "[colors.cursor]",
  "cursor = " .. q(c.fg),
  "text = " .. q(c.bg),
  "",
  "[colors.selection]",
  "background = " .. q(c.visual),
  "text = " .. q("CellForeground"),
  "",
  "[colors.normal]",
}
for i = 1, 8 do
  alacritty[#alacritty + 1] = ("%s = %s"):format(names[i], q(t[i]))
end
alacritty[#alacritty + 1] = ""
alacritty[#alacritty + 1] = "[colors.bright]"
for i = 1, 8 do
  alacritty[#alacritty + 1] = ("%s = %s"):format(names[i], q(t[i + 8]))
end
write("extras/alacritty/tanuki-night.toml", alacritty)

local function list(from, to)
  local out = {}
  for i = from, to do
    out[#out + 1] = q(t[i])
  end
  return "[" .. table.concat(out, ", ") .. "]"
end
write("extras/wezterm/tanuki-night.toml", {
  "# " .. header,
  "[colors]",
  "foreground = " .. q(c.fg),
  "background = " .. q(c.bg),
  "cursor_bg = " .. q(c.fg),
  "cursor_fg = " .. q(c.bg),
  "cursor_border = " .. q(c.fg),
  "selection_bg = " .. q(c.visual),
  "selection_fg = " .. q(c.fg),
  "split = " .. q(c.border),
  "ansi = " .. list(1, 8),
  "brights = " .. list(9, 16),
  "",
  "[metadata]",
  'name = "tanuki-night"',
  'origin_url = "https://github.com/MNnazrul/tanuki-night.nvim"',
})
