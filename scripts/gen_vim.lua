-- Generate colors/tanuki-night.vim and colors/tanuki-day.vim (plain Vim, no Lua).
-- Run from repo root:  nvim --headless -u NONE -l scripts/gen_vim.lua
vim.opt.rtp:prepend(vim.fn.getcwd())

for _, style in ipairs({ "night", "day" }) do
  local name = "tanuki-" .. style
  local hl = require("tanuki-night").highlights(style)

  local names = {}
  for name in pairs(hl) do
    if not name:find("^@") then
      names[#names + 1] = name
    end
  end
  table.sort(names)

  local function attrs(spec)
    local list = {}
    for _, a in ipairs({ "bold", "italic", "underline", "undercurl", "strikethrough", "reverse" }) do
      if spec[a] then
        list[#list + 1] = a
      end
    end
    return #list > 0 and table.concat(list, ",") or "NONE"
  end

  local out = {
    ('" %s: GitLab %s syntax theme for Vim.'):format(name, style == "day" and "light" or "dark"),
    '" GENERATED by scripts/gen_vim.lua. Edit the Lua sources instead.',
    '" Neovim reads colors/*.vim before *.lua, so hand off to the full Lua theme there.',
    "if has('nvim')",
    ("  runtime colors/%s.lua"):format(name),
    "  finish",
    "endif",
    "",
    "set background=" .. (style == "day" and "light" or "dark"),
    "hi clear",
    "if exists('syntax_on') | syntax reset | endif",
    ("let g:colors_name = '%s'"):format(name),
    "set termguicolors",
    "",
  }
  local links = {}
  for _, name in ipairs(names) do
    local spec = hl[name]
    if type(spec) == "string" or spec.link then
      links[#links + 1] = ("hi! link %s %s"):format(name, type(spec) == "string" and spec or spec.link)
    elseif next(spec) ~= nil then
      out[#out + 1] = ("hi %s guifg=%s guibg=%s guisp=%s gui=%s cterm=%s"):format(
        name,
        spec.fg or "NONE",
        spec.bg or "NONE",
        spec.sp or "NONE",
        attrs(spec),
        attrs(spec)
      )
    end
  end
  out[#out + 1] = ""
  vim.list_extend(out, links)

  vim.fn.writefile(out, "colors/" .. name .. ".vim")
  print(("wrote colors/%s.vim (%d groups)"):format(name, #names))
end
